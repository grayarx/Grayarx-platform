/**
 * Get models for a specific make
 */
export function getModelsForMake(make: string): string[] {
  return VEHICLE_MODELS[make.toLowerCase()] || [];
}

/**
 * Get all makes
 */
export function getAllMakes(): string[] {
  return Object.keys(VEHICLE_MODELS).map((m) => m.charAt(0).toUpperCase() + m.slice(1));
}
